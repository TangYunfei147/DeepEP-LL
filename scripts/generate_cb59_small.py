#!/usr/bin/env python3
"""Generate a small-direct compile specialization from the verified cb59 replay.

The original replay remains untouched. Only the two runtime mode fields become
compile-time constants, and branches whose entire condition is that constant
become if-constexpr. The inverse normalization is checked against the existing
immutable replay business-token fixture, including every synchronization call.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "csrc/kernels/dispatch/low_latency"
SOURCE = BASE / "cb59"
DEST = BASE / "cb59_small"
MANIFEST = ROOT / "tests/ll_stage_timer/fixtures/cb59_small_tokens.json"
REPLAY_MANIFEST = ROOT / "tests/ll_stage_timer/fixtures/cb59_replay_tokens.json"
spec = importlib.util.spec_from_file_location("cb59_replay_generator", ROOT / "scripts/generate_cb59_replay.py")
replay = importlib.util.module_from_spec(spec)
assert spec.loader is not None
spec.loader.exec_module(replay)
FILES = replay.FILES
BANNER = "// Generated by scripts/generate_cb59_small.py; edit the generator, not this file.\n"


def replace_once(source: str, old: str, new: str) -> str:
    return replay.replace_once(source, old, new)


def specialize(relative: str, source: str) -> str:
    source = source.replace("namespace DispatchDedup::Cb59Replay", "namespace DispatchDedup::Cb59Small")
    source = source.replace("DISPATCH_SERVER_DEDUP_", "CB59_SMALL_DISPATCH_SERVER_DEDUP_")
    if relative == FILES[1]:
        source = replace_once(source, "        useAllCoreCount_ = bs < kEpServerDedupAllCoreCountBsThreshold;\n", "")
        source = replace_once(source, "    bool useAllCoreCount_ = false;",
                              "    static constexpr bool useAllCoreCount_ = true;")
    elif relative in (FILES[2], FILES[3]):
        source = replace_once(source, "        enableDedup_ = enableDedup;", "        (void)enableDedup;")
        source = replace_once(source, "    bool enableDedup_ = false;",
                              "    static constexpr bool enableDedup_ = false;")
        # Mixed conditions retain their runtime operands. In particular,
        # !enableDedup_ && !keepFlags still depends on this packet's layout.
        source = source.replace("if (enableDedup_)", "if constexpr (enableDedup_)")
        source = source.replace("if (!enableDedup_)", "if constexpr (!enableDedup_)")
        if relative == FILES[3]:
            source = replace_once(source, "        const bool firstHop = enableDedup_ &&",
                                  "        constexpr bool firstHop = enableDedup_ &&")
            source = source.replace("if (firstHop)", "if constexpr (firstHop)")
    return BANNER + source


def unspecialize(relative: str, source: str) -> str:
    source = source.removeprefix(BANNER)
    source = source.replace("namespace DispatchDedup::Cb59Small", "namespace DispatchDedup::Cb59Replay")
    source = source.replace("CB59_SMALL_DISPATCH_SERVER_DEDUP_", "DISPATCH_SERVER_DEDUP_")
    if relative == FILES[1]:
        source = replace_once(source, "    static constexpr bool useAllCoreCount_ = true;",
                              "    bool useAllCoreCount_ = false;")
        source = replace_once(source, "        expertTokenNumsType_ = expertTokenNumsType;\n",
                              "        expertTokenNumsType_ = expertTokenNumsType;\n"
                              "        useAllCoreCount_ = bs < kEpServerDedupAllCoreCountBsThreshold;\n")
    elif relative in (FILES[2], FILES[3]):
        source = replace_once(source, "        (void)enableDedup;", "        enableDedup_ = enableDedup;")
        source = replace_once(source, "    static constexpr bool enableDedup_ = false;",
                              "    bool enableDedup_ = false;")
        source = source.replace("if constexpr (enableDedup_)", "if (enableDedup_)")
        source = source.replace("if constexpr (!enableDedup_)", "if (!enableDedup_)")
        if relative == FILES[3]:
            source = replace_once(source, "        constexpr bool firstHop = enableDedup_ &&",
                                  "        const bool firstHop = enableDedup_ &&")
            source = source.replace("if constexpr (firstHop)", "if (firstHop)")
    return source


def digest(value: object) -> str:
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, separators=(",", ":")).encode("utf-8")).hexdigest()


def validate_file(relative: str, source: str, replay_entry: dict) -> None:
    if replay.includes(source) != replay_entry["replay_includes"]:
        raise ValueError(f"{relative}: the shared include/ABI dependencies changed")
    # An unmodified copy is not an acceptable specialization, even though its
    # runtime behavior on small inputs would match. Validate constants first.
    if relative == FILES[1]:
        if source.count("static constexpr bool useAllCoreCount_ = true;") != 1:
            raise ValueError("small count participation must be a compile-time true constant")
        if "useAllCoreCount_ = bs" in source:
            raise ValueError("small count participation must not be set at runtime")
    elif relative in (FILES[2], FILES[3]):
        if source.count("static constexpr bool enableDedup_ = false;") != 1:
            raise ValueError("small dispatch must make dedup a compile-time false constant")
        if "enableDedup_ = enableDedup;" in source:
            raise ValueError("small dispatch must not initialize a runtime dedup member")
        if "if (enableDedup_)" in source or "if (!enableDedup_)" in source:
            raise ValueError("constant-only dedup branches must use if constexpr")
    normalized = unspecialize(relative, source)
    replay.validate_file(relative, normalized, replay_entry)


def generate(check: bool = False) -> dict:
    reference = json.loads(REPLAY_MANIFEST.read_text(encoding="utf-8"))
    entries = {}
    for relative in FILES:
        original = (SOURCE / relative).read_text(encoding="utf-8")
        entry = reference["files"][relative]
        replay.validate_file(relative, original, entry)
        generated = specialize(relative, original)
        validate_file(relative, generated, entry)
        destination = DEST / relative
        if check:
            actual = destination.read_text(encoding="utf-8")
            validate_file(relative, actual, entry)
            if actual != generated:
                raise ValueError(f"{relative}: generated specialization is stale")
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(generated, encoding="utf-8", newline="\n")
        entries[relative] = {
            "replay_business_sha256": digest(entry["business_tokens"]),
            "normalized_business_sha256": digest(replay.business_tokens(unspecialize(relative, generated))),
            "specialized_sha256": hashlib.sha256(generated.encode("utf-8")).hexdigest(),
            "replay_synchronization_sha256": digest(entry["synchronization"]),
            "normalized_synchronization_sha256": digest(replay.synchronization(unspecialize(relative, generated))),
        }
    manifest = {
        "reference_commit": replay.REFERENCE,
        "source_fixture": "cb59_replay_tokens.json",
        "specialization": "1<=B<=M<=32; all original EP domains and seven dtype entries",
        "changes": ["enableDedup_ is static constexpr false", "useAllCoreCount_ is static constexpr true",
                    "constant-only if statements use if constexpr", "receiver firstHop is constexpr false"],
        "unchanged": ["routing", "record and packet ownership", "UB allocations and budgets", "event IDs",
                      "synchronization ordering", "all public output metadata", "the default cb59 selector"],
        "files": entries,
    }
    if check:
        if json.loads(MANIFEST.read_text(encoding="utf-8")) != manifest:
            raise ValueError("small specialization manifest is stale")
    else:
        MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="read-only regeneration and business/sync verification")
    args = parser.parse_args()
    generate(args.check)
    print("cb59-small specialization and normalized cb59 business/synchronization checks passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
